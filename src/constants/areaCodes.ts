export const AREA_CODES: ReadonlySet<string> = new Set(AREA_CODE_LIST);

/** Strip trunk 0 / country 62, then split into area code and subscriber. */
export function splitLandline(
  nationalDigits: string,
): { code: string; subscriber: string } | undefined {
  if (nationalDigits.startsWith("8")) return undefined;
  const three = nationalDigits.slice(0, 3);
  if (AREA_CODES.has(three)) {
    return { code: three, subscriber: nationalDigits.slice(3) };
  }
  const two = nationalDigits.slice(0, 2);
  if (AREA_CODES.has(two)) {
    return { code: two, subscriber: nationalDigits.slice(2) };
  }
  return undefined;
}
